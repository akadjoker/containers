#!/usr/bin/env python3
"""Writes tests/unicode_case_cases.inc with what Node (V8/ICU) returns for
String.prototype.toUpperCase/toLowerCase: every code point that changes, plus
Final_Sigma contexts and random mixed strings (as UTF-16 hex code unit lists).

    python3 tests/gen_unicode_case_cases.py
"""
import json
import os
import random
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "unicode_case_cases.inc")

NODE = r"""
const input = JSON.parse(require('fs').readFileSync(0, 'utf8'));
const u = a => String.fromCharCode(...a);
const units = s => { const r = []; for (let i = 0; i < s.length; i++) r.push(s.charCodeAt(i)); return r; };
const out = {single: [], strings: []};
if (input.scan) {
  for (let cp = 0; cp <= 0x10FFFF; cp++) {
    if (cp >= 0xD800 && cp <= 0xDFFF) continue;
    const s = String.fromCodePoint(cp);
    const up = s.toUpperCase(), lo = s.toLowerCase();
    if (up !== s || lo !== s) out.single.push([cp, units(up), units(lo)]);
  }
  const both = [];
  for (let cp = 0; cp <= 0x10FFFF; cp++) {
    if (cp >= 0xD800 && cp <= 0xDFFF) continue;
    const s = String.fromCodePoint(cp);
    if (/\p{Cased}/u.test(s) && /\p{Case_Ignorable}/u.test(s)) both.push(cp);
  }
  out.both = both;
}
for (const a of input.strings) {
  const s = u(a);
  out.strings.push([a, units(s.toUpperCase()), units(s.toLowerCase())]);
}
process.stdout.write(JSON.stringify(out));
"""


def run(payload):
    p = subprocess.run(["node", "-e", NODE], input=json.dumps(payload).encode(), capture_output=True, check=True)
    return json.loads(p.stdout)


def hexs(a):
    return " ".join("%04X" % x for x in a)


def u(s):
    b = s.encode("utf-16-le", "surrogatepass")
    return [b[i] | (b[i + 1] << 8) for i in range(0, len(b), 2)]


def main():
    first = run({"scan": True, "strings": []})
    both = first["both"]
    ctx = ["ΣΑΣ ΣΑ", "AΣ", "ΑΣ.", "ΑΣb", "Σ", "ΑΣ́", "Α.Σ", "Α.Σ.", "ΑΣΑ", "ΑΣ́Α", "ΑΣ ", "ΑΣ­", "Σ́Α", "aΣʰ",
           "aΣʰb", "ΣΣ", "ΑΣΣ", "ΑΣΣΑ", "ΑΣ\ud800", "\ud800Σ", "Α\ud800Σ", "ΑΣ\ud800Α", "ΑΣ😀", "Α😀Σ",
           "ß", "ŉ", "ﬁ", "ﬃ", "İ", "iİI", "ǰ", "ΐ", "ᾳ", "ᾀ", "ᾼ", "ẞ", "ÿµ", "𐐀", "𐐨", "a𐐀b𐐨", "\ud801", "\udc00\ud801", "𐐀\ud801",
           "ǅ", "ǈ", "ǋ", "ǲ", "ϴ", "ς", "ᲀ", "Ꭰ", "ꭰ", "Ω", "K", "Å", "ı", "ſ", "ὒ", "ᾇ", "ᾗ", "ᾧ"]
    rnd = random.Random(7)
    pool = [0x41, 0x61, 0x7a, 0x20, 0x2e, 0xdf, 0xb5, 0xff, 0xe9, 0xc9, 0x130, 0x131, 0x149, 0x3a3, 0x3c3, 0x3c2, 0x391, 0x3b1, 0x301, 0x345,
            0xad, 0x2b0, 0x10400, 0x10428, 0xd800, 0xdc00, 0xfb01, 0x1f80, 0x1fb3, 0x1e9e, 0x4e00, 0x1f600, 0x27, 0x2019, 0x387, 0x1e900, 0x1e922]
    pool += both[:12]
    strs = []
    for s in ctx:
        strs.append(u(s))
    for cp in both:
        strs.append(u("aΣ") + [cp] + u("b"))
        strs.append(u("aΣ") + [cp] + u("Σ"))
        strs.append(u("aΣ") + [cp])
        strs.append(u("Σ") + [cp] + u("a"))
    for _ in range(3000):
        n = rnd.randint(1, 8)
        a = []
        for _ in range(n):
            cp = rnd.choice(pool)
            if cp >= 0x10000:
                cp -= 0x10000
                a += [0xD800 + (cp >> 10), 0xDC00 + (cp & 0x3FF)]
            else:
                a.append(cp)
        strs.append(a)
    res = run({"scan": False, "strings": strs})
    w = []
    w.append("// Generated by tests/gen_unicode_case_cases.py from Node %s (Unicode %s). Do not edit." % (
        subprocess.check_output(["node", "-p", "process.version"]).decode().strip(),
        subprocess.check_output(["node", "-p", "process.versions.unicode"]).decode().strip()))
    w.append("static const CaseRow kCaseSingles[] = {")
    for cp, up, lo in first["single"]:
        w.append('    {0x%X, "%s", "%s"},' % (cp, hexs(up), hexs(lo)))
    w.append("};")
    w.append("static const CaseStr kCaseStrings[] = {")
    for a, up, lo in res["strings"]:
        w.append('    {"%s", "%s", "%s"},' % (hexs(a), hexs(up), hexs(lo)))
    w.append("};")
    with open(OUT, "w") as fh:
        fh.write("\n".join(w) + "\n")
    print("wrote", OUT, len(first["single"]), "single rows,", len(res["strings"]), "strings,", len(both), "cased+case-ignorable cps")


main()
